function applyLanguage(lang) {
  const dict = i18n[lang] || i18n['es'];
  const fallbackDict = i18n['es'];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = dict[key] || fallbackDict[key] || el.textContent;
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = dict[key] || fallbackDict[key] || el.placeholder;
  });
}


function getUserId() {
  const raw = sessionStorage.getItem('sb-bazgtcrhrifsxyrwzfpk-auth') || localStorage.getItem('sb-bazgtcrhrifsxyrwzfpk-auth');
  if (raw) {
    try {
      const parsed = JSON.parse(raw);
      if (parsed.user && parsed.user.id) return parsed.user.id;
    } catch(e) {}
  }
  return 'default';
}

function loadPreferences() {
  const uid = getUserId();
  const lang = localStorage.getItem('appLang_' + uid) || 'es';
  const theme = localStorage.getItem('appTheme_' + uid) || 'light';

  applyLanguage(lang);

  if (theme === 'dark') {
    document.body.classList.add('dark-mode');
  } else {
    document.body.classList.remove('dark-mode');
  }

  const selectLang = document.getElementById('select-idioma');
  const toggleDark = document.getElementById('toggle-dark-mode');

  if (selectLang) selectLang.value = lang;
  if (toggleDark) toggleDark.checked = (theme === 'dark');
}

function savePreferences() {
  const uid = getUserId();
  const selectLang = document.getElementById('select-idioma');
  const toggleDark = document.getElementById('toggle-dark-mode');

  if (selectLang) {
    localStorage.setItem('appLang_' + uid, selectLang.value);
    applyLanguage(selectLang.value);
  }

  if (toggleDark) {
    const isDark = toggleDark.checked;
    localStorage.setItem('appTheme_' + uid, isDark ? 'dark' : 'light');
    if (isDark) {
      document.body.classList.add('dark-mode');
    } else {
      document.body.classList.remove('dark-mode');
    }
  }

  if(typeof showToast === 'function') {
    showToast('⚙️', 'Preferencias guardadas exitosamente');
  } else {
    alert('Preferencias guardadas');
  }
}

document.addEventListener('DOMContentLoaded', loadPreferences);


document.addEventListener('DOMContentLoaded', () => {
  const select = document.getElementById('select-idioma');
  const savedLang = localStorage.getItem('appLang') || 'es';
  
  if (select) {
    select.value = savedLang;
    applyLanguage(savedLang);
    select.addEventListener('change', (e) => {
      const newLang = e.target.value;
      localStorage.setItem('appLang', newLang);
      applyLanguage(newLang);
    });
  } else {
    applyLanguage(savedLang);
  }
});
